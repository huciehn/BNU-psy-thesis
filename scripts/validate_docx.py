"""Independent OOXML checks. Exit 0=accepted, 1=errors, 2=review still required."""
import argparse
import hashlib
import json
import re
import sys
import zipfile
from pathlib import Path
from lxml import etree

NS = {"w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main",
      "m": "http://schemas.openxmlformats.org/officeDocument/2006/math",
      "r": "http://schemas.openxmlformats.org/officeDocument/2006/relationships",
      "wp": "http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing"}
W = "{" + NS["w"] + "}"
ROOT = Path(__file__).resolve().parents[1]


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def parse(data):
    return etree.fromstring(data, etree.XMLParser(resolve_entities=False, no_network=True))


def attr(element, key, default=None):
    return element.get(W + key, default) if element is not None else default


def on(element):
    return element is not None and attr(element, "val", "1") not in ("0", "false", "off")


def own_text(p):
    # A text box contains a nested paragraph; do not count its text twice.
    return "".join(t.text or "" for t in p.findall(".//w:t", NS)
                   if next(t.iterancestors(W + "p"), None) is p)


def signature(parts, plan=None, original=False):
    doc = parse(parts["word/document.xml"])
    pnodes = doc.findall(".//w:body//w:p", NS)
    skip_ps = set()
    if plan and original:
        for pid, item in plan.get("paragraphs", {}).items():
            if item.get("role") in ("toc1", "toc2", "toc3"):
                idx = int(pid[1:])
                if idx < len(pnodes): skip_ps.add(pnodes[idx])
    # Cached TOC results are regenerated by Office. Keep their field instructions
    # and validate their formatting separately, but exclude them from prose diff.
    field_stack, dynamic_nodes = [], set()
    for n in doc.iter():
        if n.tag == W + "fldChar":
            kind = attr(n, "fldCharType")
            if kind == "begin": field_stack.append({"code": "", "result": False})
            elif kind == "separate" and field_stack: field_stack[-1]["result"] = True
            elif kind == "end" and field_stack: field_stack.pop()
        elif n.tag == W + "instrText" and field_stack:
            field_stack[-1]["code"] += n.text or ""
        elif any(f["result"] and re.search(r"\bTOC\b", f["code"]) for f in field_stack):
            dynamic_nodes.add(n)
    text = []
    for p in pnodes:
        if p in skip_ps: continue
        buf = []
        for n in p.iter():
            if next(n.iterancestors(W + "p"), None) is not p:
                continue
            if any(a.tag in (W + "pPr", W + "rPr") for a in n.iterancestors()):
                continue
            if n in dynamic_nodes:
                continue
            if n.tag in (W + "t", "{" + NS["m"] + "}t"):
                buf.append(n.text or "")
            elif n.tag == W + "tab":
                buf.append("\t")
            elif n.tag in (W + "br", W + "cr") and attr(n, "type") != "page":
                buf.append("\n")
        combined = "".join(buf)
        if combined:
            text.append(combined)
    symbols = [sorted(n.attrib.items()) for n in doc.findall(".//w:sym", NS)]
    def math_node(n):
        # Office can add empty formatting properties and namespace prefixes;
        # compare expression structure and values rather than serialization.
        local = etree.QName(n).localname
        if local in ("rPr", "ctrlPr", "bookmarkStart", "bookmarkEnd", "proofErr", "commentRangeStart", "commentRangeEnd", "commentReference"):
            return None
        children = [v for v in (math_node(c) for c in n) if v is not None]
        return [etree.QName(n).namespace, local, sorted(n.attrib.items()), n.text or "", children]
    formulas = [math_node(n) for n in doc.findall(".//m:oMath", NS)]
    media = {n: hashlib.sha256(b).hexdigest() for n, b in parts.items() if n.startswith("word/media/") and not n.endswith("/")}
    return {"text": hashlib.sha256(json.dumps(text, ensure_ascii=False).encode()).hexdigest(),
            "symbols": symbols,
            "formulas": hashlib.sha256(json.dumps(formulas, ensure_ascii=False).encode()).hexdigest(), "media": media}


def load_parts(path):
    with zipfile.ZipFile(path) as z:
        return {n: z.read(n) for n in z.namelist()}


def validate(path, plan, original=None, review=None, mode="thesis", language="cn"):
    profile = json.loads((ROOT / "references/profile.json").read_text(encoding="utf-8"))
    parts = load_parts(path)
    doc = parse(parts["word/document.xml"])
    ps = doc.findall(".//w:body//w:p", NS)
    styles = parse(parts["word/styles.xml"]) if "word/styles.xml" in parts else None
    style_by_id = {attr(s, "styleId"): s for s in styles.findall("w:style", NS)} if styles is not None else {}

    def style_chain(style_id, visited=None):
        visited = set() if visited is None else visited
        if not style_id or style_id in visited or style_id not in style_by_id:
            return []
        visited.add(style_id)
        style = style_by_id[style_id]
        return style_chain(attr(style.find("w:basedOn", NS), "val"), visited) + [style]

    def effective_rpr(run, p):
        containers = []
        if styles is not None:
            containers.append(styles.find("w:docDefaults/w:rPrDefault/w:rPr", NS))
        paragraph_style = attr(p.find("w:pPr/w:pStyle", NS), "val")
        containers.extend(s.find("w:rPr", NS) for s in style_chain(paragraph_style))
        direct = run.find("w:rPr", NS)
        character_style = attr(direct.find("w:rStyle", NS), "val") if direct is not None else None
        containers.extend(s.find("w:rPr", NS) for s in style_chain(character_style))
        containers.append(direct)
        result = etree.Element(W + "rPr")
        for container in containers:
            if container is None: continue
            for child in container:
                old = result.find(child.tag)
                if old is None:
                    old = etree.SubElement(result, child.tag)
                if child.tag == W + "rFonts":
                    for font, theme in (("ascii", "asciiTheme"), ("hAnsi", "hAnsiTheme"), ("eastAsia", "eastAsiaTheme"), ("cs", "cstheme")):
                        if attr(child, font) and not attr(child, theme):
                            old.attrib.pop(W + theme, None)
                if child.tag == W + "color" and attr(child, "val") and not attr(child, "themeColor"):
                    for key in ("themeColor", "themeTint", "themeShade"):
                        old.attrib.pop(W + key, None)
                old.attrib.update(child.attrib)
                old.text = child.text
        return result

    def effective_ppr(p):
        containers = []
        if styles is not None:
            containers.append(styles.find("w:docDefaults/w:pPrDefault/w:pPr", NS))
        sid = attr(p.find("w:pPr/w:pStyle", NS), "val")
        containers.extend(s.find("w:pPr", NS) for s in style_chain(sid))
        containers.append(p.find("w:pPr", NS))
        result = etree.Element(W + "pPr")
        for container in containers:
            if container is None: continue
            for child in container:
                old = result.find(child.tag)
                if old is None: old = etree.SubElement(result, child.tag)
                old.attrib.update(child.attrib)
                old.text = child.text
                if child.tag == W + "tabs":
                    old[:] = [etree.fromstring(etree.tostring(c)) for c in child]
        return result
    report = {"docx_sha256": digest(path), "profile": profile["id"], "mode": mode,
              "errors": [], "warnings": [], "pending_reviews": [], "checks": {}}

    def error(rule, location, message):
        report["errors"].append({"rule": rule, "location": location, "message": message})

    def warning(rule, location, message):
        report["warnings"].append({"rule": rule, "location": location, "message": message})

    def blank_paragraph(p):
        return (p is not None and not own_text(p).strip()
                and not p.findall(".//w:drawing", NS) and not p.findall(".//w:pict", NS)
                and not p.findall(".//m:oMath", NS) and not p.findall(".//w:instrText", NS))

    if plan.get("profile") != profile["id"]:
        error("PROFILE", "plan", "The plan does not select the bundled profile")
    mapped = {}
    positions = {}
    for i, p in enumerate(ps):
        for mark in p.findall(".//w:bookmarkStart", NS):
            if next(mark.iterancestors(W + "p"), None) is not p:
                continue
            name = attr(mark, "name", "")
            if name.startswith("bnu_psy_thesis_p"):
                pid = name[len("BNU-psy-thesis_"):]
                if pid in mapped:
                    error("PLAN", pid, "Duplicate role bookmark")
                mapped[pid], positions[pid] = p, i

    roles = dict(plan.get("paragraphs", {}))
    generated_toc_count = 0
    for i, p in enumerate(ps):
        if not own_text(p).strip(): continue
        sid = attr(p.find("w:pPr/w:pStyle", NS), "val")
        definition = style_by_id.get(sid)
        labels = [sid or ""]
        if definition is not None:
            labels.append(attr(definition.find("w:name", NS), "val", ""))
        toc_role = next(("toc" + match.group(1) for label in labels
                         for match in [re.fullmatch(r"(?:toc|目录)\s*([1-3])", label, re.I)] if match), None)
        if not toc_role: continue
        generated_toc_count += 1
        if not any(value is p for value in mapped.values()):
            pid = "generated_toc_" + str(i)
            mapped[pid], positions[pid] = p, i
            roles[pid] = {"role": toc_role}
    seen_roles = [item.get("role") for item in roles.values()]
    if mode == "thesis":
        for role in profile["requirements"]["mandatory_roles"]:
            if role not in seen_roles:
                error("COMPLETE", role, "Required thesis component is missing")
    elif mode == "proposal":
        for role in ("heading1", "body", "reference_heading", "reference"):
            if role not in seen_roles:
                error("COMPLETE", role, "Required proposal component is missing")

    for pid, item in roles.items():
        role = item.get("role")
        if role not in profile["styles"]:
            error("ROLE", pid, "Unknown paragraph role")
            continue
        p = mapped.get(pid)
        if p is None:
            if role in ("toc1", "toc2", "toc3") and generated_toc_count:
                # F9 replaces cached TOC paragraphs and their mapping bookmarks.
                # The actual regenerated entries above are checked instead.
                continue
            error("PLAN", pid, "Role bookmark is missing; cannot verify this paragraph")
            continue
        spec = dict(profile["defaults"], **profile["styles"][role])
        if role == "table_cell":
            parent = next(p.iterancestors(W + "tbl"), None)
            table_nodes = doc.findall(".//w:body//w:tbl", NS)
            if parent is not None:
                table_id = "t{:05d}".format(table_nodes.index(parent))
                if plan.get("tables", {}).get(table_id, {}).get("kind") == "form":
                    spec = dict(profile["defaults"], **profile["styles"]["form_cell"])
        if spec.get("preserve"):
            continue
        ppr = effective_ppr(p)
        if ppr is None:
            error("PARAGRAPH", pid, "No explicit paragraph properties")
            continue
        text = own_text(p)
        position = positions[pid]
        if role in ("abstract_label_cn", "abstract_label_en", "toc_title", "keywords_cn", "keywords_en"):
            if position == 0 or not blank_paragraph(ps[position - 1]):
                error("BLANK_LINE", pid, "A real empty paragraph is required before this component")
        if role in ("abstract_label_cn", "abstract_label_en", "toc_title"):
            if position + 1 >= len(ps) or not blank_paragraph(ps[position + 1]):
                error("BLANK_LINE", pid, "A real empty paragraph is required after this component")
        if role == "image":
            maximum = profile["page"].get("detector_max_image_mm", 150) * 36000
            for extent in p.findall(".//wp:extent", NS):
                if int(extent.get("cx", "0")) > maximum:
                    error("IMAGE_WIDTH", pid, "Image width exceeds the detector-compatible limit")
        jc = ppr.find("w:jc", NS)
        if attr(jc, "val") != spec["align"]:
            error("ALIGN", pid, "Expected alignment " + spec["align"])
        ind = ppr.find("w:ind", NS)
        for key, expected in (("firstLineChars", spec.get("first_line_chars", 0)),
                              ("leftChars", spec.get("left_chars", 0)),
                              ("hangingChars", spec.get("hanging_chars", 0))):
            actual = attr(ind, key, "0")
            if float(actual) != expected * 100:
                error("INDENT", pid, "{} must be {} hundredths of a character".format(key, expected * 100))
        spacing = ppr.find("w:spacing", NS)
        has_art = bool(p.findall(".//w:drawing", NS) or p.findall(".//w:pict", NS)
                       or p.findall(".//m:oMath", NS))
        if has_art or spec.get("line_pt") is None:
            if attr(spacing, "lineRule", "auto") == "exact":
                error("CLIPPING", pid, "Images, equations and table content must not use exact line height")
        else:
            if attr(spacing, "lineRule") != "exact" or attr(spacing, "line") != str(round(spec["line_pt"] * 20)):
                error("LINE", pid, "Expected fixed {} pt line spacing".format(spec["line_pt"]))
        if spec.get("line_multiple") and not has_art:
            if attr(spacing, "line", "240") != str(round(spec["line_multiple"] * 240)):
                error("LINE", pid, "Incorrect multiple line spacing")
        for side in ("before", "after"):
            expected = round(spec.get(side + "_lines", 0) * 100)
            if int(attr(spacing, side + "Lines", "0")) != expected:
                error("SPACE", pid, "Incorrect {} spacing in line units".format(side))
        if spec.get("keep_next") and not on(ppr.find("w:keepNext", NS)):
            error("KEEP", pid, "Heading/caption may be separated from following content")
        if "outline_level" in spec:
            if attr(ppr.find("w:outlineLvl", NS), "val") != str(spec["outline_level"]):
                error("OUTLINE", pid, "Incorrect heading outline level")
        chars = []
        for run in p.findall(".//w:r", NS):
            if next(run.iterancestors(W + "p"), None) is not p:
                continue
            rt = "".join(t.text or "" for t in run.findall("./w:t", NS))
            if not rt:
                continue
            rp = effective_rpr(run, p)
            fonts = rp.find("w:rFonts", NS) if rp is not None else None
            size = rp.find("w:sz", NS) if rp is not None else None
            if attr(size, "val") != str(round(spec["size_pt"] * 2)):
                error("FONT_SIZE", pid, "Incorrect run size")
            if spec.get("font_color") and attr(rp.find("w:color", NS), "val") != spec["font_color"]:
                error("FONT_COLOR", pid, "Formatting baseline requires neutral black text")
            expected_cn = spec["cn_font"]
            if role == "keywords_cn" and rt.startswith("关键词"):
                expected_cn = "黑体"
            if re.search(r"[\u3400-\u9fff]", rt) and attr(fonts, "eastAsia") != expected_cn:
                error("FONT_CN", pid, "Incorrect Chinese font")
            if re.search(r"[A-Za-z0-9]", rt):
                if attr(fonts, "ascii") != spec["en_font"] or attr(fonts, "hAnsi") != spec["en_font"]:
                    error("FONT_EN", pid, "Latin text/numbers must use Times New Roman")
            if fonts is not None and any(attr(fonts, k) for k in ("asciiTheme", "hAnsiTheme", "eastAsiaTheme")):
                error("FONT_THEME", pid, "Theme font override is still active")
            b = rp.find("w:b", NS) if rp is not None else None
            italic = rp.find("w:i", NS) if rp is not None else None
            if "bold" in spec and on(b) != spec["bold"]:
                error("BOLD", pid, "Incorrect bold formatting")
            chars.extend((ch, on(italic), on(b)) for ch in rt)
        for span in item.get("spans", []):
            start, end = span["start"], span["end"]
            if not (0 <= start < end <= len(chars)):
                error("SPANS", pid, "Invalid inline formatting range")
                continue
            for field, idx in (("italic", 1), ("bold", 2)):
                if field in span and any(c[idx] != span[field] for c in chars[start:end]):
                    error("SPANS", pid, "Inline {} range does not match plan".format(field))
        if role == "reference" and not any(c[1] for c in chars):
            warning("APA_ITALICS", pid, "No italic span; verify the work type and required italic fields")
        if role in ("heading1", "heading2", "heading3", "heading4", "heading5"):
            match = re.match(r"^\s*(\d+(?:\.\d+)*)(\s+)(\S)", text)
            if match:
                expected_spaces = 2 if role == "heading1" else 1
                if match.group(2) != " " * expected_spaces:
                    error("HEADING_NUMBER", pid, "Heading number must be followed by {} ASCII spaces".format(expected_spaces))
            elif re.match(r"^\s*\d", text):
                error("HEADING_NUMBER", pid, "Malformed heading numbering")
        if role == "abstract_label_cn" and text.strip() != "摘  要":
            error("LABEL", pid, "Chinese abstract label must contain two spaces")
        if role == "abstract_label_en" and text.strip() != "ABSTRACT":
            error("LABEL", pid, "English abstract label must be ABSTRACT")
        if role == "toc_title" and text.strip() not in ("目  录", "Contents"):
            error("LABEL", pid, "Incorrect contents title")
        if role in ("toc1", "toc2", "toc3"):
            tab = ppr.find('w:tabs/w:tab[@w:val="right"]', NS)
            if tab is None or attr(tab, "leader") != "middleDot":
                error("TOC_TAB", pid, "TOC page numbers need a right tab with a middle-dot leader")
        if role == "ack_heading" and text.strip() not in ("致  谢", "Acknowledgements"):
            error("LABEL", pid, "Incorrect acknowledgements title")
        if role == "keywords_cn":
            if not text.startswith("关键词：") or text.startswith("关键词： "):
                error("KEYWORDS", pid, "Expected 关键词： without a space after colon")
            count = len(text.partition("：")[2].split("，"))
            if not 3 <= count <= 5:
                error("KEYWORDS", pid, "The detection system accepts 3–5 Chinese keywords separated by fullwidth commas")
            if len(chars) >= 4 and (not all(c[2] for c in chars[:4]) or any(c[2] for c in chars[4:])):
                error("KEYWORD_BOLD", pid, "Only the Chinese keyword label must be bold")
        if role == "keywords_en":
            if not text.startswith("KEY WORDS: "):
                error("KEYWORDS", pid, "Expected KEY WORDS: followed by one space")
            if len(chars) >= 10 and (not all(c[2] for c in chars[:10]) or any(c[2] for c in chars[10:])):
                error("KEYWORD_BOLD", pid, "Only the English keyword label must be bold")
        if role in ("figure_caption", "table_caption"):
            caption = re.match(r"^(图|表)(\s*)(\d+)(.*)$", text)
            if caption:
                if caption.group(2):
                    error("CAPTION_NUMBER", pid, "Do not insert whitespace between 图/表 and its number")
                if not re.match(r"^ \S", caption.group(4)):
                    error("CAPTION_NUMBER", pid, "Use exactly one ASCII space between the number and caption text")
        if role == "figure_caption" and text.rstrip().endswith((".", "。")):
            error("FIGURE_CAPTION", pid, "A figure caption must not end in a full stop")
        if role == "table_note" and text and not text.rstrip().endswith((".", "。")):
            error("TABLE_NOTE", pid, "Table notes need a final full stop")
        if re.search(r"\*\*\S[^*]+\*\*", text):
            warning("MARKDOWN", pid, "Possible unrendered Markdown; significance stars remain legitimate")
        if role in ("body", "table_cell", "table_note", "figure_note", "table_caption", "figure_caption"):
            plain = "".join(c[0] for c in chars)
            for match in re.finditer(r"(?<![A-Za-z])(SD|SE|M|N|n|t|F|df|p|r|R|d|f|z)(?=\s*(?:[=<>（(]|检验|值))", plain):
                if not all(c[1] for c in chars[match.start():match.end()]):
                    error("STAT_ITALICS", pid, "An unambiguous statistical symbol needs real italic formatting")
            if any(c[1] for c in chars if c[0] in "αβγΔηθλΛνρΣτφχΨω"):
                error("GREEK_UPRIGHT", pid, "Greek statistical letters must remain upright")

    cn_kw = [own_text(mapped[k]).partition("：")[2].split("，") for k,v in roles.items() if k in mapped and v.get("role") == "keywords_cn"]
    en_kw = [own_text(mapped[k]).partition(": ")[2].split(", ") for k,v in roles.items() if k in mapped and v.get("role") == "keywords_en"]
    if cn_kw and en_kw and len(cn_kw[0]) != len(en_kw[0]):
        error("KEYWORD_PAIR", "document", "Chinese and English keyword counts differ")
    chinese_ref_seen = False
    for pid, item in roles.items():
        if item.get("role") != "reference" or pid not in mapped: continue
        authors = own_text(mapped[pid]).split(".", 1)[0]
        chinese = bool(re.search(r"[\u3400-\u9fff]", authors))
        if chinese: chinese_ref_seen = True
        elif chinese_ref_seen: error("REFERENCE_ORDER", pid, "English references must precede Chinese references")

    # Verify each physical section's properties and footer references, not cached page numbers.
    sections = []
    start = 0
    for i, p in enumerate(ps):
        s = p.find("./w:pPr/w:sectPr", NS)
        if s is not None:
            sections.append((start, i, s))
            start = i + 1
    final = doc.find("./w:body/w:sectPr", NS)
    if final is not None:
        sections.append((start, len(ps) - 1, final))
    if not sections:
        error("SECTION", "document", "No section properties")
    body_positions = [positions[p] for p, v in roles.items() if v.get("role") == "heading1" and p in positions]
    first_body = min(body_positions) if body_positions else None
    rels = parse(parts["word/_rels/document.xml.rels"])
    rel_targets = {r.get("Id"): r.get("Target") for r in rels}
    for si, (begin, end, section) in enumerate(sections):
        where = "section{}".format(si + 1)
        pg = section.find("w:pgSz", NS)
        landscape = attr(pg, "orient") == "landscape"
        for key, mm in (("w", 297 if landscape else 210), ("h", 210 if landscape else 297)):
            if abs(int(attr(pg, key, "0")) - round(mm / 25.4 * 1440)) > 2:
                error("PAGE_SIZE", where, "Expected A4 paper size")
        mar = section.find("w:pgMar", NS)
        for key in ("top", "left", "bottom", "right"):
            if abs(int(attr(mar, key, "0")) - round(profile["page"][key + "_mm"] / 25.4 * 1440)) > 2:
                error("MARGIN", where, "Incorrect {} margin".format(key))
        in_body = first_body is not None and begin >= first_body
        footer_refs = section.findall("w:footerReference", NS)
        has_page = False
        for ref in footer_refs:
            target = rel_targets.get(ref.get("{" + NS["r"] + "}id"), "")
            target_name = target.lstrip("/") if target.startswith("/") else "word/" + target
            if target_name not in parts:
                error("FOOTER", where, "Footer target missing")
                continue
            footer = parse(parts[target_name])
            fields = " ".join(t.text or "" for t in footer.findall(".//w:instrText", NS))
            fields += " " + " ".join(attr(t, "instr", "") for t in footer.findall(".//w:fldSimple", NS))
            if re.search(r"\bPAGE\b", fields):
                has_page = True
                for fp in footer.findall(".//w:p", NS):
                    fp_fields = " ".join(t.text or "" for t in fp.findall(".//w:instrText", NS))
                    fp_fields += " " + " ".join(attr(t, "instr", "") for t in fp.findall(".//w:fldSimple", NS))
                    if not re.search(r"\bPAGE\b", fp_fields):
                        continue
                    if attr(fp.find("w:pPr/w:jc", NS), "val") != "center":
                        error("FOOTER", where, "Page-number footer must be centered")
                    for run in fp.findall(".//w:r", NS):
                        if not (run.findall(".//w:instrText", NS) or run.findall(".//w:fldChar", NS) or run.findall(".//w:t", NS)):
                            continue
                        rp = effective_rpr(run, fp)
                        if attr(rp.find("w:sz", NS), "val") != "18":
                            error("FOOTER", where, "Page-number font size must be 9pt")
                        elif attr(rp.find("w:rFonts", NS), "ascii") != "Times New Roman":
                            error("FOOTER", where, "Page-number font must be Times New Roman")
        if in_body and not has_page:
            error("FOOTER", where, "Body/back matter requires an explicit PAGE footer")
        if not in_body and has_page:
            error("FOOTER", where, "Front matter must not have visible page numbers")
        if first_body is not None and begin == first_body:
            num = section.find("w:pgNumType", NS)
            if attr(num, "start") != "1" or attr(num, "fmt") != "decimal":
                error("PAGE_RESTART", where, "Body numbering must restart at Arabic 1")
        elif in_body and attr(section.find("w:pgNumType", NS), "start") is not None:
            error("PAGE_RESTART", where, "Later sections must continue page numbering")
    odd_roles = set(profile["requirements"]["odd_section_roles"])
    appendix_seen = False
    for pid, item in roles.items():
        role = item.get("role")
        must_odd = role in odd_roles or (role == "heading1" and positions.get(pid) == first_body)
        if role == "appendix_heading_multi" and not appendix_seen:
            must_odd = True
            appendix_seen = True
        if not must_odd or pid not in positions:
            continue
        idx = positions[pid]
        matched = next((s for begin, end, s in sections if begin == idx), None)
        if matched is None or attr(matched.find("w:type", NS), "val") != "oddPage":
            error("ODD_SECTION", pid, "This component must begin an odd-page section")

    tbls = doc.findall(".//w:body//w:tbl", NS)
    for tid, item in plan.get("tables", {}).items():
        try:
            table = tbls[int(tid[1:])]
        except (ValueError, IndexError):
            error("TABLE", tid, "Table in plan is missing")
            continue
        if item.get("kind") != "data":
            continue
        if attr(table.find("./w:tblPr/w:jc", NS), "val") != "center":
            error("TABLE_ALIGN", tid, "A data table must be centered")
        grid_width = sum(int(attr(node, "w", "0")) for node in table.findall("./w:tblGrid/w:gridCol", NS))
        if grid_width > round(profile["page"].get("detector_max_table_mm", 150) * 1440 / 25.4):
            error("TABLE_WIDTH", tid, "Table grid exceeds the detector-compatible width")
        borders = table.find("./w:tblPr/w:tblBorders", NS)
        for side, expected in (("top", 8), ("bottom", 8)):
            edge = borders.find("w:" + side, NS) if borders is not None else None
            if attr(edge, "sz") != str(expected) or attr(edge, "val") != "single":
                error("TABLE_LINE", tid, "Top/bottom border must be 1pt")
        if borders is not None:
            for side in ("left", "right", "insideV", "insideH"):
                edge = borders.find("w:" + side, NS)
                if edge is not None and attr(edge, "val") not in ("nil", "none"):
                    error("TABLE_LINE", tid, "Unexpected table grid border")
        rows = table.findall("./w:tr", NS)
        header_rows = item.get("header_rows", 1)
        for ri, row in enumerate(rows):
            if not on(row.find("./w:trPr/w:cantSplit", NS)):
                error("TABLE_ROW", tid, "A table row may split across pages")
            if ri < header_rows and not on(row.find("./w:trPr/w:tblHeader", NS)):
                error("TABLE_HEADER", tid, "Header rows must repeat")
        if rows and header_rows:
            header = rows[header_rows - 1]
            for cell in header.findall("./w:tc", NS):
                bottom = cell.find("./w:tcPr/w:tcBorders/w:bottom", NS)
                if attr(bottom, "val") != "single" or attr(bottom, "sz") != "4":
                    error("TABLE_LINE", tid, "Header separating line must be 0.5pt")

    toc_fields = [t.text or "" for t in doc.findall(".//w:instrText", NS)]
    toc_fields += [attr(t, "instr", "") for t in doc.findall(".//w:fldSimple", NS)]
    if mode == "thesis" and not any(re.search(r'\bTOC\b.*\\o\s+"1-3"', f) for f in toc_fields):
        error("TOC", "document", 'An automatic TOC field for levels "1-3" is required')
    if original:
        if digest(original) != plan.get("input_sha256"):
            error("INPUT_BINDING", "original", "Original hash does not match plan")
        before, after = signature(load_parts(original), plan, True), signature(parts, plan)
        if before != after:
            error("PRESERVATION", "document", "Text, equations, symbols or image bytes changed")
        report["checks"]["content_preserved"] = before == after
    else:
        report["pending_reviews"].append("original_file_preservation")
    body_text = "".join(own_text(mapped[pid]) for pid, item in roles.items()
                        if pid in mapped and item.get("role") in ("body", "heading1", "heading2", "heading3"))
    count = len(re.findall(r"[\u3400-\u9fff]", body_text))
    report["checks"]["body_chinese_chars"] = count
    if mode != "partial" and language == "cn" and count < 8000:
        warning("BODY_LENGTH", "document", "Body is below the general 8000 Chinese-character requirement; do not pad or invent content")
    report["pending_reviews"].extend(profile["requirements"]["review_checks"])
    for name, check in (("word/footnotes.xml", "footnotes_format_and_integrity"), ("word/endnotes.xml", "endnotes_format_and_integrity")):
        if name in parts and parse(parts[name]).findall(".//w:t", NS):
            report["pending_reviews"].append(check)
    if doc.findall(".//w:numPr", NS):
        report["pending_reviews"].append("automatic_numbering_font_and_alignment")
    if doc.findall(".//w:highlight", NS) or doc.findall(".//w:shd", NS):
        report["pending_reviews"].append("editorial_shading_and_highlights_intentional")
    if "word/comments.xml" in parts:
        report["pending_reviews"].append("comments_intentional_or_resolved")
    if review:
        if review.get("docx_sha256") != report["docx_sha256"]:
            error("REVIEW_BINDING", "review", "Review belongs to a different output version")
        elif not review.get("rendered_pdf_sha256") or not review.get("reviewer"):
            error("REVIEW_EVIDENCE", "review", "Render hash and reviewer record are required")
        else:
            completed = review.get("checks", {})
            report["pending_reviews"] = [k for k in report["pending_reviews"] if completed.get(k) is not True]
    if mode == "partial":
        report["pending_reviews"].append("partial_document_is_not_a_complete_thesis")
    report["structural_pass"] = not report["errors"]
    report["ready_to_submit"] = report["structural_pass"] and not report["pending_reviews"]
    return report


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("input", type=Path)
    p.add_argument("--plan", type=Path, required=True)
    p.add_argument("--original", type=Path)
    p.add_argument("--review", type=Path)
    p.add_argument("--mode", choices=("thesis", "proposal", "partial"), default="thesis")
    p.add_argument("--language", choices=("cn", "en"), default="cn")
    p.add_argument("--report", type=Path, required=True)
    p.add_argument("--structural-only", action="store_true", help="Exit 0 for structural pass; never implies final acceptance")
    args = p.parse_args()
    if args.report.exists():
        p.error("Refusing to overwrite an existing report")
    if args.report.resolve() == args.input.resolve():
        p.error("Report and input paths must differ")
    plan = json.loads(args.plan.read_text(encoding="utf-8"))
    review = json.loads(args.review.read_text(encoding="utf-8")) if args.review else None
    try:
        result = validate(args.input, plan, args.original, review, args.mode, args.language)
    except (ValueError, KeyError, OSError, etree.XMLSyntaxError, zipfile.BadZipFile) as exc:
        result = {"structural_pass": False, "ready_to_submit": False, "errors": [{"rule": "INPUT", "message": str(exc)}]}
    args.report.parent.mkdir(parents=True, exist_ok=True)
    with args.report.open("x", encoding="utf-8") as handle:
        json.dump(result, handle, ensure_ascii=False, indent=2)
    print("structural_pass={}, ready_to_submit={}, errors={}, pending={}".format(
        result["structural_pass"], result["ready_to_submit"], len(result["errors"]), len(result.get("pending_reviews", []))))
    sys.exit(1 if not result["structural_pass"] else (0 if result["ready_to_submit"] or args.structural_only else 2))


if __name__ == "__main__":
    main()
